"""Copies the icons listed in game/data/art.json into game/art/icons/.

Icons come from game-icons.net (CC BY 3.0). Usage, from the repository root:

    git clone --depth 1 https://github.com/game-icons/icons.git /tmp/game-icons
    python3 tools/import_icons.py /tmp/game-icons

Each icon is saved as game/art/icons/<name>.svg with its black background
removed and the shape filled white, so the game can tint it any color.
It also rewrites the icon list in CREDITS.md.
"""
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ART = os.path.join(ROOT, "game", "data", "art.json")
OUT = os.path.join(ROOT, "game", "art", "icons")
CREDITS = os.path.join(ROOT, "CREDITS.md")
MARKER = "<!-- icon list (generated by tools/import_icons.py) -->"


def all_refs(art):
    refs = set()
    for section in ("cards", "emotes", "player_icons", "ui"):
        refs.update(art[section].values())
    for icons in art["arenas"].values():
        refs.update(icons)
    return sorted(refs)


def main():
    source = sys.argv[1]
    art = json.load(open(ART))
    os.makedirs(OUT, exist_ok=True)
    names = {}
    for ref in all_refs(art):
        author, name = ref.split("/")
        if names.get(name, author) != author:
            sys.exit(f"Two icons are both called '{name}' ({names[name]} and {author}); pick one")
        names[name] = author
        svg = open(os.path.join(source, author, name + ".svg")).read()
        svg = re.sub(r'<path d="M0 0h512v512H0z"\s*/>', "", svg)
        svg = re.sub(r'fill="#[0-9a-fA-F]{3,6}"', 'fill="#fff"', svg)
        open(os.path.join(OUT, name + ".svg"), "w").write(svg)
    for file_name in os.listdir(OUT):
        if file_name.endswith(".svg") and file_name[:-4] not in names:
            os.remove(os.path.join(OUT, file_name))
            print("removed unused", file_name)

    by_author = {}
    for name, author in sorted(names.items()):
        by_author.setdefault(author, []).append(name)
    lines = [MARKER, ""]
    for author, icons in sorted(by_author.items()):
        lines.append(f"- **{author}**: {', '.join(icons)}")
    text = open(CREDITS).read()
    text = text[: text.index(MARKER)] + "\n".join(lines) + "\n"
    open(CREDITS, "w").write(text)
    print(f"{len(names)} icons from {len(by_author)} artists")


if __name__ == "__main__":
    main()
